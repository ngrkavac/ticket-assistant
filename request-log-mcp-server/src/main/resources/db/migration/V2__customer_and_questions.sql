-- Requests can be asked on behalf of a customer; older rows have none.
ALTER TABLE request_log ADD COLUMN customer VARCHAR(64);

CREATE INDEX idx_request_log_customer_created_at ON request_log (customer, created_at DESC);

-- Questions offered in the UI; users can add more.
CREATE TABLE question_catalog (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text       VARCHAR(1000) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

